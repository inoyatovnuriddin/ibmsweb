export type AppLanguage = 'uz' | 'ru' | 'uz-Cyrl';

export const DEFAULT_LANGUAGE: AppLanguage = 'uz';
export const LANGUAGE_STORAGE_KEY = 'ibms-language';

export const normalizeAppLanguage = (value?: string | null): AppLanguage => {
  if (value === 'ru') return 'ru';
  if (value === 'uz-Cyrl' || value === 'uz-cyrl') return 'uz-Cyrl';
  return 'uz';
};

export const readAppLanguage = (): AppLanguage => {
  if (typeof window === 'undefined') {
    return DEFAULT_LANGUAGE;
  }

  return normalizeAppLanguage(window.localStorage.getItem(LANGUAGE_STORAGE_KEY));
};

export const saveAppLanguage = (language: AppLanguage) => {
  if (typeof window === 'undefined') return;
  window.localStorage.setItem(LANGUAGE_STORAGE_KEY, language);
};

export const setApiLanguage = (language: AppLanguage) => {
  saveAppLanguage(language);
};

export const getBackendLanguageCode = (language?: string | null): AppLanguage =>
  normalizeAppLanguage(language);

