export const translate = (
  language: AppLanguage,
  key: TranslationKey
): string => {
  return translations[language]?.[key] || translations[DEFAULT_LANGUAGE][key] || key;
};

export const getApiErrorMessage = (error: unknown, fallback = 'Xatolik yuz berdi') => {
  const normalized = error as {
    response?: { data?: { errors?: { message?: string; details?: string }; message?: string; detail?: string } };
    message?: string;
  };

  return (
    normalized?.response?.data?.errors?.message ||
    normalized?.response?.data?.errors?.details ||
    normalized?.response?.data?.detail ||
    normalized?.response?.data?.message ||
    normalized?.message ||
    fallback
  );
};

export type { TranslationKey };
